import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const db = new PGlite();
const A = '10000000-0000-4000-8000-000000000001';
const B = '10000000-0000-4000-8000-000000000002';
const C = '10000000-0000-4000-8000-000000000003';
let groupId, invite, taskId, otherGroup;
async function as(id, role = 'authenticated') {
  await db.exec('reset role');
  await db.query("select set_config('request.jwt.claim.sub', $1, false)", [id || '']);
  await db.exec(`set role ${role}`);
}
async function rpc(sql, args = []) { return (await db.query(sql, args)).rows[0].result; }

before(async () => {
  await db.exec(`
    create role authenticated; create role anon;
    create schema auth;
    create function auth.uid() returns uuid language sql stable as $$
      select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
    $$;
    grant usage on schema auth, public to authenticated, anon;
    create table public.profiles(id uuid primary key, created_at timestamptz not null default now(), username text, email text, avatar_url text);
    create table public.groups(id bigint generated by default as identity primary key, created_at timestamptz not null default now(), name text not null, created_by uuid not null references profiles(id), invite_code text unique not null);
    create table public.group_members(id bigint generated by default as identity primary key, created_at timestamptz not null default now(), user_id uuid not null references profiles(id), group_id bigint not null references groups(id) on delete cascade);
    create table public.tasks(id bigint generated by default as identity primary key, created_at timestamptz not null default now(), title text not null, due_date timestamptz, category text, priority text, is_completed boolean not null default false, user_id uuid not null references profiles(id), assigned_to uuid references profiles(id) on delete set null, group_id bigint references groups(id) on delete cascade);
    insert into profiles(id,username,email) values ('${A}','Same Name','private-a@example.com'),('${B}','Same Name','private-b@example.com'),('${C}','Outsider','private-c@example.com');
    -- Simulate a previous broad policy: new restrictive guards must still isolate data.
    create policy legacy_allow_all on public.tasks for all to authenticated using(true) with check(true);
    create policy legacy_allow_profiles on public.profiles for select to authenticated using(true);
  `);
  await db.exec(await readFile(new URL('../supabase/setup-all.sql', import.meta.url), 'utf8'));
  const groupSQL = await readFile(new URL('../supabase/setup-groups.sql', import.meta.url), 'utf8');
  await db.exec(groupSQL);
  await db.exec(groupSQL); // Migration must be rerunnable without deleting data.
});
after(async () => { await db.close(); });

test('create group atomically includes creator and returns a private unique invite', async () => {
  await as(A);
  groupId = (await rpc('select public.donee_create_group($1) as result', ['A team'])).id;
  const groups = await rpc('select public.donee_list_groups() as result');
  invite = groups[0].invite_code;
  assert.equal(groups[0].id, groupId); assert.match(invite, /^[A-F0-9]{12}$/);
  assert.equal(groups[0].members.length, 1); assert.equal(groups[0].members[0].id, A);
  assert(!JSON.stringify(groups).includes('private-'));
});

test('outsider cannot list/read group, invite codes, members, or other profiles', async () => {
  await as(C);
  assert.deepEqual(await rpc('select public.donee_list_groups() as result'), []);
  assert.equal((await db.query('select * from groups')).rows.length, 0);
  assert.equal((await db.query('select * from group_members')).rows.length, 0);
  const profiles = (await db.query('select * from profiles')).rows;
  assert.equal(profiles.length, 1); assert.equal(profiles[0].id, C);
  await assert.rejects(() => db.query('insert into group_members(user_id,group_id) values($1,$2)', [C, groupId]), /permission denied/);
  await assert.rejects(() => rpc('select public.donee_join_group($1) as result', ['INVALID']), /รหัสเชิญไม่ถูกต้อง/);
});

test('second account joins using lowercase code; repeated join never duplicates membership', async () => {
  await as(B);
  const joined = await rpc('select public.donee_join_group($1) as result', ['  ' + invite.toLowerCase() + '  ']);
  assert.equal(joined.id, groupId); assert.equal(joined.already_joined, false);
  assert.equal((await rpc('select public.donee_join_group($1) as result', [invite])).already_joined, true);
  const groups = await rpc('select public.donee_list_groups() as result');
  assert.equal(groups[0].members.length, 2);
  assert.equal(groups[0].members[0].name, groups[0].members[1].name); // Same names remain distinct UUIDs.
});

test('group tasks persist, members share visibility, outsiders cannot access', async () => {
  await as(A);
  const row = await rpc('select public.donee_save_group_task($1,null,$2,now(),$3,$4,false) as result', [groupId,'Shared task','Group','Medium']);
  taskId = row.id;
  assert.equal(row.user_id, A);
  await as(B);
  assert.equal((await db.query('select * from tasks where id=$1', [taskId])).rows.length, 1);
  const edited = await rpc('select public.donee_save_group_task($1,$2,$3,now(),$4,$5,false) as result', [groupId,taskId,'Edited by member','Group','High']);
  assert.equal(edited.user_id, A); assert.equal(edited.title, 'Edited by member');
  await as(C);
  assert.equal((await db.query('select * from tasks where id=$1', [taskId])).rows.length, 0);
  await assert.rejects(() => rpc('select public.donee_complete_group_task($1,$2,true) as result', [groupId,taskId]), /สมาชิกกลุ่ม/);
});

test('direct group task writes are denied even with legacy permissive policies', async () => {
  await as(B);
  await assert.rejects(() => db.query('insert into tasks(title,user_id,group_id) values($1,$2,$3)', ['Bypass', B, groupId]), /row-level security/);
  const updated = await db.query('update tasks set assigned_to=$1 where id=$2 returning id', [C,taskId]);
  assert.equal(updated.rows.length, 0);
  assert.equal((await db.query('delete from tasks where id=$1 returning id', [taskId])).rows.length, 0);
});

test('batch assignment validates members and saves UUIDs; invalid batch rolls back', async () => {
  await as(A);
  const count = await rpc('select public.donee_assign_group_tasks($1,$2::jsonb) as result', [groupId,JSON.stringify([{ task_id: taskId, member_id: B }])]);
  assert.equal(count, 1);
  assert.equal((await db.query('select assigned_to from tasks where id=$1', [taskId])).rows[0].assigned_to, B);
  const second = await rpc('select public.donee_save_group_task($1,null,$2,now(),$3,$4,false) as result', [groupId,'Second','Group','Low']);
  await assert.rejects(() => rpc('select public.donee_assign_group_tasks($1,$2::jsonb) as result', [groupId,JSON.stringify([{ task_id: taskId, member_id: A },{ task_id: second.id, member_id: C }])]), /สมาชิกกลุ่ม/);
  assert.equal((await db.query('select assigned_to from tasks where id=$1', [taskId])).rows[0].assigned_to, B);
  await assert.rejects(() => rpc('select public.donee_assign_group_tasks($1,$2::jsonb) as result', [groupId,JSON.stringify([{ task_id: taskId, member_id: A },{ task_id: taskId, member_id: B }])]), /งานซ้ำ/);
});

test('completed and cross-group tasks cannot be assigned; unrelated IDs cannot be edited/deleted', async () => {
  await as(A);
  otherGroup = (await rpc('select public.donee_create_group($1) as result', ['Other'])).id;
  const foreignTask = await rpc('select public.donee_save_group_task($1,null,$2,now(),$3,$4,false) as result', [otherGroup,'Other task','Group','Low']);
  await assert.rejects(() => rpc('select public.donee_assign_group_tasks($1,$2::jsonb) as result', [groupId,JSON.stringify([{task_id:foreignTask.id,member_id:A}])]), /งานเปลี่ยนแปลง/);
  await assert.rejects(() => rpc('select public.donee_delete_group_task($1,$2) as result', [groupId,foreignTask.id]), /ไม่พบงาน/);
  await rpc('select public.donee_complete_group_task($1,$2,true) as result', [groupId,taskId]);
  await assert.rejects(() => rpc('select public.donee_assign_group_tasks($1,$2::jsonb) as result', [groupId,JSON.stringify([{task_id:taskId,member_id:A}])]), /งานเปลี่ยนแปลง/);
});

test('personal tasks still work and remain private across group members', async () => {
  await as(A);
  const row = (await db.query('insert into tasks(title,user_id) values($1,$2) returning id', ['Private',A])).rows[0];
  await as(B);
  assert.equal((await db.query('select * from tasks where id=$1',[row.id])).rows.length,0);
  await assert.rejects(() => db.query('insert into tasks(title,user_id) values($1,$2)', ['Spoof',A]), /row-level security/);
});

test('anonymous callers cannot call create/join RPCs or read tables', async () => {
  await as(null,'anon');
  await assert.rejects(() => rpc('select public.donee_create_group($1) as result', ['Anon']), /permission denied/);
  await assert.rejects(() => rpc('select public.donee_join_group($1) as result', [invite]), /permission denied/);
  await assert.rejects(() => db.query('select * from groups'), /permission denied/);
});
